import { ThemeProvider, ThemeSwitcher } from "@/components/ui/theme-provider";
import { THEME_STORAGE_KEY } from "../site.config";

/**
 * 明暗の切り替えだけを出す島。
 *
 * ----------------------------------------------------------------
 * なぜトンマナ（4 種）を出さないのか
 * ----------------------------------------------------------------
 * ここは**完成したサイトの見本**です。配色の系統は作った側が決めたもので、
 * 見に来た人が変えるものではありません（`lp.astro` は warm、
 * ブログは editorial、というように**ページごとに決めてあります**）。
 *
 * 見に来た人が変えたいのは明るさだけなので、それだけを出します。
 *
 * ----------------------------------------------------------------
 * なぜ SiteHeader の中に入れないのか
 * ----------------------------------------------------------------
 * `SiteHeader` の `actions` は React の要素を受け取りますが、
 * **`.astro` からは要素を渡せません**（props が JSON 化されるため）。
 * だから独立した島として置き、位置は CSS で決めています。
 *
 * ----------------------------------------------------------------
 * なぜ保存先を分けるのか
 * ----------------------------------------------------------------
 * localStorage は origin 単位です。カタログ（`/catalog/`）とデモ（`/demo/`）は
 * 同じドメインなので、分けないと片方の選択がもう片方にも出ます。
 */
export function ThemeToggle() {
  return (
    <ThemeProvider storageKey={THEME_STORAGE_KEY} lockTheme>
      <ThemeSwitcher themes={false} />
    </ThemeProvider>
  );
}
