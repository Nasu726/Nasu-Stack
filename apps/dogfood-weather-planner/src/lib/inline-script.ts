/**
 * `<script>` の中へ値を書き出すための直列化。
 * ================================================================
 * HTML に直接埋め込むスクリプトへ値を渡す唯一の入口です。
 *
 * ```ts
 * const src = `var key = ${toInlineScriptJson(storageKey)};`;
 * ```
 *
 * ----------------------------------------------------------------
 * なぜ `JSON.stringify` だけでは足りないのか
 * ----------------------------------------------------------------
 * **`<script>` の中は HTML のパーサが先に読みます。**
 * 中身に `</script` が現れると、JavaScript としての意味とは関係なく
 * **そこでスクリプトが終わります。** 残りは本文として描画され、
 * 差し込みの入口にもなります。`JSON.stringify` は `<` を逃がしません。
 *
 * U+2028 / U+2029 も逃がします。JSON では文字列の中に置けますが、
 * JavaScript では**行の区切り**として扱われるためです
 * （新しい版の JS では緩和されましたが、古い環境では壊れます）。
 *
 * ----------------------------------------------------------------
 * なぜ「引用符の中に差し込む」形をやめたのか
 * ----------------------------------------------------------------
 * v0.9d では、雛型の側にこう書いていました。
 *
 * ```js
 * localStorage.getItem("__WT_STORAGE_KEY__")   // ← 引用符の中を置換
 * ```
 *
 * この形だと、値に `"` が 1 つ入るだけで引用符から出られます。
 * **データが実行コードになります。**
 *
 * ```js
 * // storageKey = 'x");globalThis.x=1;//' を渡すと
 * localStorage.getItem("x");globalThis.x=1;//")
 * ```
 *
 * 置き換え先は**引用符の外**に置き、値のほうをこの関数でリテラルにします。
 * 外部レビューの P1-01。
 */
export function toInlineScriptJson(value: unknown): string {
  return (JSON.stringify(value) ?? "null")
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}
