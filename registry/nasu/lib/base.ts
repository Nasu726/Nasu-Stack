/**
 * サブパスに公開したときも、リンクが壊れないようにします。
 *
 * ================================================================
 * なぜ必要なのか
 * ================================================================
 * サイトを `https://example.com/` の直下ではなく、
 * `https://example.com/my-site/` のような**下の階層**に置くことがあります。
 * GitHub Pages にリポジトリ単位で公開すると、必ずこの形になります。
 *
 * そのとき `astro.config.mjs`（や `vite.config.ts`）に `base` を書きます。
 * ところが **`base` が効くのは、道具が自動で出す部分だけ**です。
 *
 *   効く   … 画像・CSS・JS など、ビルドが吐き出すファイルの場所
 *   効かない … **あなたが手で書いた `href="/about/"`**
 *
 * つまり `/about/` と書いたリンクは、公開すると
 * `https://example.com/about/` を指し続けます。
 * 実体は `https://example.com/my-site/about/` にあるので、404 です。
 *
 * ================================================================
 * なぜ気づきにくいのか
 * ================================================================
 * **手元では絶対に再現しません。** 開発サーバは直下で動くので、
 * `/about/` がそのまま正解になります。壊れるのは公開した後だけです。
 *
 * v0.9b で実際にやりました。公開したデモは、ページ間のリンクが**全部** 404
 * でしたが、こちらの検査は緑のままでした（資材の URL しか見ていなかったため）。
 *
 * だから **`SiteHeader` / `SiteFooter` は、受け取った `href` に自動で付けます。**
 * 「覚えておいてもらう」形にすると、書き忘れても手元では気づけないので、
 * 必ず漏れます。
 *
 * ページの本文に手で書くリンクには、この関数を直接使ってください。
 *
 * ```tsx
 * <a href={withBase("/contact/")}>お問い合わせ</a>
 * ```
 */

/**
 * 公開先の下の階層。`import.meta.env.BASE_URL` は Astro と Vite の両方が
 * 用意します（直下なら `"/"`）。
 */
function currentBase(): string {
  const raw =
    (typeof import.meta !== "undefined" &&
      (import.meta as { env?: Record<string, string> }).env?.BASE_URL) ||
    "/";
  // 末尾のスラッシュだけ落として揃えます（"/" は "" になります）
  return raw.replace(/\/$/, "");
}

/**
 * 必要なときだけ、パスの先頭に公開先の階層を足します。
 *
 * **触ってはいけないものは触りません。** この関数の仕事の半分はそれです。
 *
 * | 渡したもの | どうなるか |
 * |---|---|
 * | `/about/` | 足す |
 * | `https://…` `//…` | そのまま（外部） |
 * | `#top` `mailto:` `tel:` | そのまま |
 * | `./x` `../x` `x` | そのまま（相対はもともと正しく解決されます） |
 * | 既に足してあるもの | **そのまま**（二重に足しません） |
 *
 * 最後の行が要です。部品が自動で足すので、利用者が自分で足した場合と
 * 重なります。**二重に足すと、直したつもりで壊れます。**
 */
export function withBase(path: string): string {
  if (!path) return path;

  // 外部・スキーム付き・アンカー。こちらの管轄ではありません。
  if (/^([a-z][a-z0-9+.-]*:|\/\/|#)/i.test(path)) return path;

  // 相対パス。ブラウザが今いる場所から解決するので、足すと壊れます。
  if (!path.startsWith("/")) return path;

  const base = currentBase();
  if (!base) return path;

  // 既に足してある。`/my-site` と `/my-site-2` を取り違えないよう、
  // 区切りまで見ます。
  if (path === base || path.startsWith(`${base}/`)) return path;

  return `${base}${path}`;
}
